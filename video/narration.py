def heights_text():
    """Narration for the counter-height scene; every number is read from the result files."""
    R = OUT.parents[1] / "results" / "experiments"
    ev = json.loads((R / "multiheight_load_dishwasher.json").read_text())
    ex = json.loads((R / "multiheight_extrap_load_dishwasher.json").read_text())
    pp = ev["per_policy"]
    pc = lambda v: f"{round(v * 100)} percent"
    s_tr, s_te = pp["bc_single_height"]["train_heights"], pp["bc_single_height"]["test_heights"]
    m_tr, m_te = pp["bc_multi_height"]["train_heights"], pp["bc_multi_height"]["test_heights"]
    lo, hi = ex["rows"]
    return (f"One limit we then tried to remove: counter height. The dishwasher policy trained at eighty-five centimetres scores "
            f"{pc(s_tr['per_height']['0.850'])} there, but only {pc(s_tr['success'])} across the four training heights and {pc(s_te['success'])} on held-out heights. "
            f"The scripted expert solves every height we probed, so the fault is the learned policy. Training on thirty demonstrations at each of four heights "
            f"gives {pc(m_tr['success'])} on those heights and {pc(m_te['success'])} on held-out heights inside the range. "
            f"It does not extrapolate: {pc(lo['success'])} at {lo['counter_height']:.2f} metres, and {pc(hi['success'])} at {hi['counter_height']:.2f}. "
            f"One seed, one task.")


async def _tts(name, text):
    OUT.mkdir(parents=True, exist_ok=True)
    await edge_tts.Communicate(text, VOICE, rate=RATE).save(str(OUT / f"{name}.mp3"))


def duration(path):
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    r = subprocess.run([ff, "-i", str(path)], capture_output=True, text=True)
    for line in r.stderr.splitlines():
        if "Duration:" in line:
            h, m, s = line.split("Duration:")[1].split(",")[0].strip().split(":")
            return int(h) * 3600 + int(m) * 60 + float(s)
    raise RuntimeError(path)


def main(failure_text=None):
    script = dict(SCRIPT)
    f = Path(__file__).resolve().parent / "failure_text.txt"
    script["failure"] = failure_text or (f.read_text().strip() if f.exists() else "")
    script["heights"] = heights_text()
    script = {k: v for k, v in script.items() if v}
    durs = {}
    for k, v in script.items():
        asyncio.run(_tts(k, v))
        durs[k] = duration(OUT / f"{k}.mp3")
        print(k, round(durs[k], 1), "s", len(v.split()), "words", flush=True)
    (OUT / "durations.json").write_text(json.dumps({"voice": VOICE, "rate": RATE, "durations": durs, "script": script}, indent=1))
    print("total", round(sum(durs.values()), 1))


if __name__ == "__main__":
    main()
