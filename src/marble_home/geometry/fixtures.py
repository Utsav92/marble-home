"""SYNTHETIC stand-ins for a Marble collision-mesh export (used by CI and offline development).

These are NOT real Marble outputs. They mimic the documented *structure* of an export (glTF +Y-up GLB with
non-metric raw units, a ground-plane offset and a ``World``-like json with semantics_metadata) and contain
deliberate defects (floating fragments, a duplicated object) so the processing pipeline is genuinely exercised.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import trimesh

YUP = np.array([[1, 0, 0], [0, 0, 1], [0, -1, 0]], dtype=float)  # metric Z-up -> glTF Y-up : (x,y,z)->(x,z,-y)


def _box(center, size):
    b = trimesh.creation.box(extents=size)
    b.apply_translation(center)
    return b


def make_kitchen_meshes(width=5.0, depth=4.0, height=2.7, seed=0, with_junk=True) -> list[trimesh.Trimesh]:
    """Room in METRIC Z-up coordinates, floor top at z=0, centred on the origin."""
    rng = np.random.default_rng(seed)
    t = 0.10  # wall thickness
    parts = [
        _box([0, 0, -0.05], [width, depth, 0.10]),                                   # floor slab (top at z=0)
        _box([0, depth / 2 + t / 2, height / 2], [width + 2 * t, t, height]),          # +y wall
        _box([width / 2 + t / 2, 0, height / 2], [t, depth, height]),                  # +x wall
        _box([-width / 2 - t / 2, 0, height / 2], [t, depth, height]),                 # -x wall
        _box([-1.6, -depth / 2 - t / 2, height / 2], [width - 3.2, t, height]),        # -y wall with a doorway gap
        _box([1.7, -depth / 2 - t / 2, height / 2], [width - 3.4, t, height]),
        _box([0, -depth / 2 - t / 2, 2.4], [1.0, t, height - 2.4]),                    # door lintel
        _box([0, depth / 2 - 0.35, 0.45], [width - 0.4, 0.6, 0.9]),                    # counter run along +y wall (0.9 m)
        _box([0.0, depth / 2 - 0.2, 1.75], [width - 1.0, 0.35, 0.7]),                  # upper cabinets
        _box([-1.4, -0.6, 0.375], [1.3, 0.8, 0.75]),                                   # dining table top block
    ]
    for lx, ly in [(-1.9, -0.9), (-0.9, -0.9), (-1.9, -0.3), (-0.9, -0.3)]:            # table legs
        parts.append(_box([lx + 0.0, ly, 0.37], [0.05, 0.05, 0.74]))
    chair = [_box([-1.4, -1.5, 0.22], [0.4, 0.4, 0.44]), _box([-1.4, -1.68, 0.7], [0.4, 0.04, 0.5])]
    parts += chair
    parts += [m.copy() for m in chair]  # duplicated geometry (identical chair at the same place)
    if with_junk:  # floating mesh fragments a generative model might emit
        for _ in range(6):
            parts.append(_box(rng.uniform([-2, -1.5, 0.5], [2, 1.5, 2.0]), [0.04, 0.03, 0.05]))
    return parts


def write_fixture(out_dir: str | Path, scene_id: str = "kitchen_fixture_001", scale: float = 1.25, ground_offset: float = 0.30,
                  seed: int = 0, **room) -> Path:
    """Write <out_dir>/{collider.glb, world.json, README.txt}. Raw coords = (metric + offset) / scale, Y-up."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    meshes = make_kitchen_meshes(seed=seed, **room)
    scene = trimesh.Scene()
    for i, m in enumerate(meshes):
        g = m.copy()
        v = np.asarray(g.vertices) @ YUP.T          # Z-up -> Y-up
        v[:, 1] += ground_offset                    # ground plane offset (metres, applied after scale in the pipeline)
        g.vertices = v / scale                       # raw (non-metric) units
        scene.add_geometry(g, node_name=f"part_{i:03d}", geom_name=f"part_{i:03d}")
    scene.export(out / "collider.glb")
    world = {
        "_synthetic": True,
        "world_id": f"synthetic-{scene_id}", "display_name": scene_id, "model": "synthetic-fixture",
        "world_prompt": {"type": "text", "text_prompt": "SYNTHETIC fixture: 5x4x2.7 m kitchen (not a Marble generation)"},
        "assets": {"mesh": {"collider_mesh_url": "local:collider.glb"},
                   "splats": {"semantics_metadata": {"metric_scale_factor": scale, "ground_plane_offset": ground_offset}}},
    }
    (out / "world.json").write_text(json.dumps(world, indent=2))
    (out / "README.txt").write_text("SYNTHETIC test fixture generated by marble_home.geometry.fixtures. Not a real Marble export.\n")
    return out
