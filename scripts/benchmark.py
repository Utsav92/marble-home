"""Benchmark all policies on IDENTICAL held-out instance seeds; paired statistics; markdown + plot from logged data.

    python scripts/benchmark.py --config configs/evaluation.yaml --auto
Outputs: results/benchmark/<task>.json, reports/benchmark_<task>.md, reports/benchmark_<task>.png
"""
from __future__ import annotations

import argparse
import glob
import time
from pathlib import Path

import numpy as np

from marble_home.evaluation.metrics import mcnemar_exact, summarize
from marble_home.evaluation.rollout import evaluate
from marble_home.utils import provenance
from marble_home.utils.cli import load_cfg
from marble_home.utils.paths import CHECKPOINTS, REPORTS, RESULTS, ensure


def discover(task: str) -> list[dict]:
    specs = []
    for p in sorted(glob.glob(str(CHECKPOINTS / "*.pt")) + glob.glob(str(CHECKPOINTS / "*.zip"))):
        n = Path(p).stem
        if task not in n:
            continue
        spec = {"name": n, "type": "ppo" if p.endswith(".zip") else "checkpoint", "path": p}
        if n.startswith("diffusion"):
            spec["ddim_steps"] = 10
        specs.append(spec)
    return specs


def plot(task, rows, path):
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    names = [r["name"] for r in rows]
    sr = np.array([r["summary"]["success_rate"] for r in rows])
    lo = np.array([r["summary"]["success_ci95"][0] for r in rows])
    hi = np.array([r["summary"]["success_ci95"][1] for r in rows])
    fig, ax = plt.subplots(figsize=(max(5, 1.4 * len(rows)), 4))
    ax.bar(range(len(rows)), sr, yerr=[sr - lo, hi - sr], capsize=4, color="#3b82f6")
    ax.set_xticks(range(len(rows)))
    ax.set_xticklabels(names, rotation=30, ha="right", fontsize=8)
    ax.set_ylim(0, 1.05)
    ax.set_ylabel("success rate (Wilson 95% CI)")
    ax.set_title(f"{task}: held-out instances, n={rows[0]['summary']['n']}")
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    plt.close(fig)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="configs/evaluation.yaml")
    ap.add_argument("--task", default=None)
    ap.add_argument("--auto", action="store_true", help="also evaluate every checkpoint in checkpoints/ matching the task")
    ap.add_argument("--episodes", type=int, default=None)
    ap.add_argument("--workers", type=int, default=None)
    ap.add_argument("--tag", default="")
    args = ap.parse_args()
    cfg = load_cfg(args.config)
    task = args.task or cfg["task"]
    n = args.episodes or cfg["test_seeds"]["count"]
    seeds = list(range(cfg["test_seeds"]["start"], cfg["test_seeds"]["start"] + n))
    workers = args.workers or cfg.get("workers", 1)
    specs = list(cfg["policies"]) + (discover(task) if args.auto else [])
    seen, uniq = set(), []
    for s in specs:
        if s["name"] not in seen:
            uniq.append(s)
            seen.add(s["name"])
    rows = []
    for s in uniq:
        t0 = time.time()
        eps = evaluate(s, task, seeds, workers=workers, **cfg.get("env", {}))
        summ = summarize(eps)
        sps = float(np.mean([e["sim_steps_per_s"] for e in eps]))
        rows.append({"name": s["name"], "spec": s, "summary": summ, "episodes": eps, "sim_steps_per_s": sps, "wall_s": time.time() - t0})
        lo, hi = summ["success_ci95"]
        print(f"{s['name']:42s} success {summ['success_rate']:6.1%} [{lo:.1%},{hi:.1%}]  latency {summ['latency_ms']:.1f} ms  ({time.time() - t0:.0f}s)", flush=True)

    ref = next((r for r in rows if r["name"] == "scripted_expert"), rows[0])
    out_dir, rep_dir = RESULTS / "benchmark", REPORTS
    ensure(out_dir, rep_dir)
    tag = f"_{args.tag}" if args.tag else ""
    provenance.write_json(out_dir / f"{task}{tag}.json", {"task": task, "seeds": seeds, "rows": rows, "manifest": provenance.run_manifest()})
    plot(task, rows, rep_dir / f"benchmark_{task}{tag}.png")

    L = [f"# Benchmark: `{task}`", "",
         f"{n} held-out instance seeds ({seeds[0]}..{seeds[-1]}), identical for every policy (paired). Generated by `scripts/benchmark.py` from "
         f"`results/benchmark/{task}{tag}.json`; nothing here is hand-entered.", "",
         "| policy | success | 95% CI (Wilson) | grasp | place err (m) | collision-free | latency (ms) | sim steps/s | paired vs " + ref["name"] + " (McNemar p) |",
         "|---|---|---|---|---|---|---|---|---|"]
    ref_ok = {e["seed"]: e["success"] for e in ref["episodes"]}
    for r in rows:
        s = r["summary"]
        ok = {e["seed"]: e["success"] for e in r["episodes"]}
        b = sum(ok[k] and not ref_ok[k] for k in ok)
        c = sum(ref_ok[k] and not ok[k] for k in ok)
        p = "-" if r is ref else f"{mcnemar_exact(b, c):.3f} (+{b}/-{c})"
        L.append(f"| {r['name']} | {s['success_rate']:.1%} | {s['success_ci95'][0]:.1%}-{s['success_ci95'][1]:.1%} | {s['grasp_success']:.1%} | "
                 f"{s['place_error']:.3f} | {s['collision_free']:.1%} | {s['latency_ms']:.1f} | {r['sim_steps_per_s']:.1f} | {p} |")
    (rep_dir / f"benchmark_{task}{tag}.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
